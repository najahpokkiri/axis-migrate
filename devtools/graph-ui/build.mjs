// Build the vendored editor bundle: axis-migrate/skills/discover/graph.bundle.js (one file, CSS inlined, no CDN).
//   npm ci && npm run build          (node 22; versions pinned in package.json / package-lock.json)
//   npm run check                    (build to a temp file and compare with the committed bundle)
import * as esbuild from 'esbuild';
import { readFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, '..', '..', 'axis-migrate', 'skills', 'discover', 'graph.bundle.js');
const check = process.argv.includes('--check');
const out = check ? join(mkdtempSync(join(tmpdir(), 'axis-graph-ui-')), 'graph.bundle.js') : target;

const pkg = JSON.parse(readFileSync(join(here, 'package.json'), 'utf8'));
const banner = `/* axis-migrate workflow graph editor. Generated by devtools/graph-ui/build.mjs; do not edit.\n` +
  ` * Bundles: ${Object.entries(pkg.dependencies).map(([k, v]) => `${k}@${v}`).join(', ')} (MIT licences). */`;

await esbuild.build({
  entryPoints: [join(here, 'src', 'main.jsx')],
  bundle: true,
  minify: true,
  format: 'iife',
  target: ['es2020'],
  jsx: 'automatic',
  loader: { '.css': 'text', '.js': 'jsx' },
  define: { 'process.env.NODE_ENV': '"production"' },
  legalComments: 'none',
  banner: { js: banner },
  outfile: out,
  logLevel: 'warning',
});

if (check) {
  const a = readFileSync(out, 'utf8');
  const b = readFileSync(target, 'utf8');
  if (a !== b) { console.error('graph.bundle.js differs from a fresh build'); process.exit(1); }
  console.log('graph.bundle.js matches a fresh build');
} else {
  console.log(`wrote ${target} (${readFileSync(target).length} bytes)`);
}
