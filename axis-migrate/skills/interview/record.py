"""record.py — append a well-formed decision or known difference (never hand-write the YAML block).

    axpy record.py decision migration --json entry.json      # appends `## D-nnn · title · <UTC>` + yaml block
    axpy record.py kd       migration --json entry.json      # appends `## KD-nnn · title` + yaml block

entry.json holds the fields of the block plus `title` (decision: id, question, kind, answer, by, params, nodes,
changes, supersedes, evidence; KD: kind, datasets, checks, rule, bound, reason, evidence, owner, decided_at,
decision_ref, status). The next free id is assigned unless `id` is given (it must then be the next one). The YAML is
generated by a serialiser, so quoting can never break; the block is re-parsed before the file is appended, and the
append is atomic. Use `supersedes: D-nnn` (or KD-nnn) to correct an earlier entry, including a malformed one —
earlier entries are never edited (append-only; a hook enforces it).
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "lib"))
import axis_common as ac  # noqa: E402

import yaml

DEC_KEYS = ["id", "question", "kind", "answer", "by", "params", "nodes", "changes", "supersedes", "evidence"]
KD_KEYS = ["id", "kind", "datasets", "checks", "rule", "bound", "reason", "evidence", "owner", "decided_at",
           "decision_ref", "status", "supersedes"]
DEC_KINDS = {"answer", "assumption", "agent_decision", "legacy_keep", "legacy_fix", "scope", "fit_confirm", "fit_spec",
             "manual_step", "plan_approval", "target", "confirm_all", "kd_accept", "tolerance_sign"}
KD_KINDS = {"normalisation", "exclusion", "accepted_change", "legacy_defect_preserved"}


def _next_id(text: str, prefix: str) -> str:
    nums = [int(m) for m in re.findall(rf"(?m)^## {prefix}-(\d{{3}})\b", text)]
    return f"{prefix}-{(max(nums) + 1) if nums else 1:03d}"


def _block(head: str, body: dict, keys: list) -> str:
    ordered = {k: body.get(k) for k in keys if k in body or k in ("supersedes",)}
    extra = {k: v for k, v in body.items() if k not in keys}
    ordered.update(extra)
    y = yaml.safe_dump(ordered, sort_keys=False, allow_unicode=True, width=110, default_flow_style=False)
    if yaml.safe_load(y) != ordered:          # round trip must be exact
        raise ValueError("entry does not survive a YAML round trip")
    return f"\n{head}\n```yaml\n{y}```\n"


def append(mdir: Path, what: str, entry: dict) -> str:
    entry = dict(entry)
    title = str(entry.pop("title", "")).strip()
    if not title or "\n" in title or "·" in title:
        raise ValueError("title is required: one line, no '·'")
    if what == "decision":
        path, prefix, keys = mdir / "decisions.md", "D", DEC_KEYS
        if entry.get("kind") not in DEC_KINDS:
            raise ValueError(f"kind must be one of {sorted(DEC_KINDS)}")
        if not entry.get("by"):
            raise ValueError("by is required (user (AskUserQuestion) | user (graph) | user (chat) | agent)")
    else:
        path, prefix, keys = mdir / "known-differences.md", "KD", KD_KEYS
        if entry.get("kind") not in KD_KINDS:
            raise ValueError(f"kind must be one of {sorted(KD_KINDS)}")
        if entry.get("status", "proposed") not in ("proposed", "withdrawn"):
            raise ValueError("an agent writes KDs as proposed (or withdrawn); only a person accepts one")
        if str(entry.get("owner", "agent")).startswith("human"):
            raise ValueError("only a person can own a KD; write owner: agent (the person signs in SIGN-OFF.md)")
        entry.setdefault("owner", "agent")
        entry.setdefault("status", "proposed")
        entry.setdefault("decided_at", None)
    if what == "kd":
        unknown = set(entry) - set(KD_KEYS)
        if unknown:
            raise ValueError(f"unknown KD keys {sorted(unknown)}; allowed: {KD_KEYS}")
    text = path.read_text(encoding="utf-8") if path.exists() else (
        "# Decisions (append-only)\n" if what == "decision" else "# Known differences (append-only)\n")
    nid = _next_id(text, prefix)
    if entry.get("id") not in (None, nid):
        raise ValueError(f"next free id is {nid}, got {entry.get('id')}")
    entry["id"] = nid
    head = f"## {nid} · {title} · {ac.utc_now_iso()}" if what == "decision" else f"## {nid} · {title}"
    new = text.rstrip("\n") + "\n" + _block(head, entry, keys)
    ac.atomic_write_text(path, new)
    return nid


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("what", choices=["decision", "kd"])
    ap.add_argument("migration")
    ap.add_argument("--json", required=True, help="path to entry.json, or - for stdin")
    a = ap.parse_args(argv)
    raw = sys.stdin.read() if a.json == "-" else Path(a.json).read_text(encoding="utf-8")
    try:
        nid = append(Path(a.migration).resolve(), a.what, json.loads(raw))
    except (ValueError, json.JSONDecodeError) as e:
        print(f"record.py: refused: {e}", file=sys.stderr)
        return 2
    print(nid)
    return 0


if __name__ == "__main__":
    sys.exit(main())
