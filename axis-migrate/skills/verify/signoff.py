#!/usr/bin/env python3
"""signoff.py <migration> — render migration/SIGN-OFF.md: every unsigned tolerance record and every proposed known
difference, with its two measured numbers (or bound), evidence, the runs it affects and the exact lines a human must
edit to sign it.

It never signs anything. Only a human edits agreed_by/agreed_at (tolerances.yaml) or owner/status
(known-differences.md); compare.py treats anything else as unsigned (NEEDS_DECISION, never PASS).
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "lib"))
sys.path.insert(0, str(HERE))
import axis_common as ac  # noqa: E402
import compare  # noqa: E402


def _fmt(x) -> str:
    if isinstance(x, float):
        return repr(x)
    return "null" if x is None else str(x)


def _record_lines(text: str) -> dict[str, dict]:
    """Line numbers (1-based) of each record's id, agreed_by and agreed_at lines in tolerances.yaml."""
    lines = text.splitlines()
    out: dict[str, dict] = {}
    starts = []
    for i, ln in enumerate(lines):
        m = re.match(r"^(\s*)-?\s*id:\s*['\"]?([^'\"\s#]+)", ln)
        if m and m.group(2).startswith("tol."):
            starts.append((i, m.group(2)))
    for n, (i, rid) in enumerate(starts):
        end = starts[n + 1][0] if n + 1 < len(starts) else len(lines)
        info = {"id_line": i + 1, "agreed_by": None, "agreed_at": None}
        for j in range(i, end):
            if re.match(r"^\s*-?\s*agreed_by:", lines[j]):
                info["agreed_by"] = j + 1
            if re.match(r"^\s*-?\s*agreed_at:", lines[j]):
                info["agreed_at"] = j + 1
        out[rid] = info
    return out


def _kd_lines(text: str) -> dict[str, dict]:
    lines = text.splitlines()
    out: dict[str, dict] = {}
    cur = None
    for i, ln in enumerate(lines):
        m = re.match(r"^##\s+(KD-\d+)", ln)
        if m:
            cur = m.group(1)
            out[cur] = {"heading": i + 1, "owner": None, "status": None}
            continue
        if cur and re.match(r"^\s*owner:", ln) and out[cur]["owner"] is None:
            out[cur]["owner"] = i + 1
        if cur and re.match(r"^\s*status:", ln) and out[cur]["status"] is None:
            out[cur]["status"] = i + 1
    return out


def _runs_affected(mig: Path, rid: str) -> list[str]:
    runs = set()
    rdir = mig / "runs"
    if not rdir.exists():
        return []
    for run in sorted(p for p in rdir.iterdir() if p.is_dir()):
        snap = run / "snapshot" / "tolerances.yaml"
        if snap.exists() and rid in snap.read_text(encoding="utf-8"):
            runs.add(run.name)
        snapk = run / "snapshot" / "known-differences.md"
        if snapk.exists() and re.search(rf"^##\s+{re.escape(rid)}\b", snapk.read_text(encoding="utf-8"), re.M):
            runs.add(run.name)
        cdir = run / "verify" / "compare"
        if cdir.exists():
            for f in cdir.glob("*.json"):
                txt = f.read_text(encoding="utf-8")
                if rid in txt:
                    runs.add(run.name)
    return sorted(runs)


def render(migration: str | Path) -> Path:
    import yaml
    mig = Path(migration)
    out = ["# SIGN-OFF — tolerance records and known differences waiting for a human", "",
           "Generated by `skills/verify/signoff.py`. Nothing in this file is signed and nothing here signs anything:",
           "a record counts only after **you** edit the lines named below yourself. Until then `compare.py` treats",
           "it as unsigned: a check that would pass only under it is `NEEDS_DECISION` (`TOLERANCE_UNSIGNED` /",
           "`KD_UNSIGNED`), never `PASS_*`. A signature applies from the next run onwards (one verify per run).", ""]
    tpath = mig / "tolerances.yaml"
    out.append("## Tolerance records")
    out.append("")
    n_t = 0
    if tpath.exists():
        text = tpath.read_text(encoding="utf-8")
        doc = yaml.safe_load(text) or {}
        lines = _record_lines(text)
        book = compare.ToleranceBook(doc, compare.parse_time("2999-01-01T00:00:00Z", end_of_day=False))
        for i, rec in enumerate(doc.get("records") or []):
            if not isinstance(rec, dict):
                continue
            if compare._is_human(rec.get("agreed_by")) and rec.get("agreed_at"):
                continue
            n_t += 1
            rid = rec.get("id")
            st = book.status.get(i, {})
            cs, nw = rec.get("correct_spread") or {}, rec.get("nearest_wrong") or {}
            ln = lines.get(rid, {})
            out += [f"### {rid}", "",
                    f"- dataset `{rec.get('dataset')}`, check `{rec.get('check')}`, metric `{rec.get('metric')}`, "
                    f"threshold {_fmt(st.get('threshold'))} (atol {_fmt(rec.get('atol'))}, rtol {_fmt(rec.get('rtol'))}, "
                    f"max_mismatch {_fmt(rec.get('max_mismatch'))}, units {_fmt(rec.get('units'))})",
                    f"- correct spread: **{_fmt(cs.get('value'))}** — {cs.get('how') or 'how not stated'}; "
                    f"evidence {cs.get('evidence') or 'none'}",
                    f"- nearest wrong: **{_fmt(nw.get('value'))}** — {nw.get('variant') or 'variant not stated'}; "
                    f"evidence {nw.get('evidence') or 'none'}",
                    f"- two-number check: {'passes' if st.get('status') in ('unsigned', 'signed') else 'FAILS'}"
                    f"{'' if st.get('status') in ('unsigned', 'signed') else ' — ' + str(st.get('why'))}"
                    + ("" if st.get("status") in ("unsigned", "signed")
                       else " (signing it would not help: the check would still run exact)"),
                    f"- runs affected: {', '.join(_runs_affected(mig, rid)) or 'none yet'}",
                    f"- record starts at line {ln.get('id_line', '?')} of tolerances.yaml. To sign, edit:"]
            for k, hint in (("agreed_by", "<your name>"), ("agreed_at", "<UTC time before the next run, e.g. "
                                                                         "2026-10-14T09:00:00Z>")):
                if ln.get(k):
                    out.append(f"  - `tolerances.yaml:{ln[k]}`: `{k}: {_fmt(rec.get(k))}` → `{k}: {hint}`")
                else:
                    out.append(f"  - add `{k}: {hint}` to the record (no `{k}` line yet)")
            out.append("")
    if n_t == 0:
        out += ["No unsigned tolerance records.", ""]
    kpath = mig / "known-differences.md"
    out += ["## Known differences", ""]
    n_k = 0
    if kpath.exists():
        text = kpath.read_text(encoding="utf-8")
        kds, errs = compare.parse_known_differences(text)
        lines = _kd_lines(text)
        for kd in kds:
            human = isinstance(kd.get("owner"), str) and kd["owner"].startswith("human:") and \
                compare._is_human(kd["owner"][6:])
            if kd.get("status") == "withdrawn" or (kd.get("status") == "accepted" and human):
                continue
            n_k += 1
            kid = kd.get("id")
            ln = lines.get(kid, {})
            bound = kd.get("bound")
            out += [f"### {kid} ({kd.get('kind')})", "",
                    f"- datasets {kd.get('datasets')}, checks {kd.get('checks')}",
                    f"- rule `{kd.get('rule')}`; bound {bound if bound else 'none'}",
                    f"- reason: {kd.get('reason')}; evidence {kd.get('evidence')}",
                    f"- runs affected: {', '.join(_runs_affected(mig, kid)) or 'none yet'}",
                    f"- entry starts at line {ln.get('heading', '?')} of known-differences.md. To accept, edit:"]
            if ln.get("owner"):
                out.append(f"  - `known-differences.md:{ln['owner']}`: `owner: {kd.get('owner')}` → "
                           "`owner: human:<your name>`")
            if ln.get("status"):
                out.append(f"  - `known-differences.md:{ln['status']}`: `status: {kd.get('status')}` → "
                           "`status: accepted` (and set `decided_at` to the time you decide)")
            if kd.get("kind") == "accepted_change":
                out.append("  - note: an accepted_change never turns the check green; the step becomes "
                           "ACCEPTED_DIFFERENCE (amber) only if its bound holds")
            out.append("")
        for e in errs:
            out.append(f"- unreadable entry {e['id']}: {e['why']}")
    if n_k == 0:
        out += ["No proposed known differences.", ""]
    dst = mig / "SIGN-OFF.md"
    ac.atomic_write_text(dst, "\n".join(out).rstrip() + "\n")
    return dst


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="signoff.py", description=__doc__.split("\n\n")[0])
    ap.add_argument("migration")
    a = ap.parse_args(argv)
    p = render(a.migration)
    print(f"wrote {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
